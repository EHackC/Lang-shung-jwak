section ".text" code readable executable
    include "../memory.inc"
    include "../utf8.inc"

    start:
        sub rsp, 8 * 5

        call memory_init

        ; 파일 텍스트 길이 구하기
        mov rcx, _file
        mov rdx, [_file_size]
        mov r8, _text_length
        call get_utf8_text_length

        ; 메모리 할당
        mov rcx, [_text_length]
        shl rcx, 2
        call m_alloc
        mov [_output_addr], rax

        ; 디코딩
        mov rcx, _file
        mov rdx, [_file_size]
        mov r8, [_output_addr]
        call decode_utf8_list

        ; 메모리 해제
        mov rcx, [_output_addr]
        call m_free

        xor rax, rax
        call [ExitProcess]

