section ".text" code readable executable
    start:
        sub rsp, 8 * 5

        call [GetProcessHeap]
        mov [_heap_handle], rax

        mov rcx, _file
        mov rdx, [_file_size]
        mov r8, _text_length
        call get_utf8_text_length

        mov rax, [_text_length]
        shl rax, 2
        mov rcx, [_heap_handle]
        mov rdx, 0
        mov r8, rax
        call [HeapAlloc]
        mov [_output_addr], rax

        mov rcx, _file
        mov rdx, [_file_size]
        mov r8, [_output_addr]
        call decode_utf8_list

        mov rcx, [_heap_handle]
        mov rdx, 0
        mov r8, [_output_addr]
        call [HeapFree]

        mov ecx, 0
        call [ExitProcess]

